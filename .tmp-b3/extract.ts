import { readFileSync, writeFileSync } from "node:fs";
import { LEGACY_DEFINER_SEARCH_PATH } from "../scripts/security-definer-legacy";
import { definerKey, searchPathFromDef } from "../scripts/security-definer-policy";
const snap = JSON.parse(readFileSync("db/schema.snapshot.json","utf8"));
const rows = snap.functions.map((f: any) => ({ k: definerKey(f.schema,f.name,f.args), sp: searchPathFromDef(f.def), def: f.def })).filter((r: any) => LEGACY_DEFINER_SEARCH_PATH.includes(r.k));
const groups: Record<string, string[]> = {};
for (const r of rows) (groups[String(r.sp)] ??= []).push(r.k);
for (const [g, ks] of Object.entries(groups)) console.log(g, ks.length, "\n  " + ks.join("\n  "));
const picked = rows.filter((r: any) => String(r.sp) === "public,pg_temp");
writeFileSync("/tmp/b3/defs.sql", picked.map((r: any) => `\n\n===== ${r.k}\n${r.def}`).join(""));
